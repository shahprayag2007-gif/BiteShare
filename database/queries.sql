USE campus_food_db;

-- ----------------------------------------------------------------------------
-- 1. View all active, unexpired food listings in a specific city (e.g., Bengaluru)
-- ----------------------------------------------------------------------------
SELECT 
    f.listing_id,
    f.food_title,
    f.quantity_servings,
    f.food_category,
    f.food_source,
    u.name AS university_name,
    f.pickup_location,
    f.expiry_time,
    TIMESTAMPDIFF(MINUTE, NOW(), f.expiry_time) AS minutes_left_to_expire
FROM food_listings f
JOIN universities u ON f.university_id = u.university_id
WHERE f.status = 'available'
  AND f.expiry_time > NOW()
  AND u.city = 'Bengaluru'
ORDER BY f.expiry_time ASC;

-- ----------------------------------------------------------------------------
-- 2. Aggregate Query: Total servings donated and rescued by university
-- (Demonstrates GROUP BY, COUNT, SUM, and conditional aggregation)
-- ----------------------------------------------------------------------------
SELECT 
    u.name AS university_name,
    u.city,
    COUNT(f.listing_id) AS total_posts,
    COALESCE(SUM(f.quantity_servings), 0) AS total_servings_offered,
    COALESCE(SUM(CASE WHEN f.status = 'collected' THEN f.quantity_servings ELSE 0 END), 0) AS servings_rescued,
    COALESCE(SUM(CASE WHEN f.status = 'available' AND f.expiry_time > NOW() THEN f.quantity_servings ELSE 0 END), 0) AS currently_available
FROM universities u
LEFT JOIN food_listings f ON u.university_id = f.university_id
GROUP BY u.university_id, u.name, u.city
ORDER BY total_servings_offered DESC;

-- ----------------------------------------------------------------------------
-- 3. Complex JOIN: Track claims in-progress with NGO details & donor contact
-- ----------------------------------------------------------------------------
SELECT 
    c.claim_id,
    f.food_title,
    f.quantity_servings,
    u.name AS university_name,
    f.pickup_location,
    donor.full_name AS donor_name,
    donor.phone AS donor_phone,
    ngo.name AS ngo_name,
    ngo.contact_person AS ngo_contact,
    ngo.phone AS ngo_phone,
    c.volunteer_name,
    c.volunteer_phone,
    c.expected_pickup_time,
    c.claim_status
FROM claims c
JOIN food_listings f ON c.listing_id = f.listing_id
JOIN universities u ON f.university_id = u.university_id
JOIN users donor ON f.donor_id = donor.user_id
JOIN ngos ngo ON c.ngo_id = ngo.ngo_id
WHERE c.claim_status = 'active';

-- ----------------------------------------------------------------------------
-- 4. Subquery: Find verified NGOs that have NOT yet claimed any food
-- (Demonstrates NOT IN / NOT EXISTS subqueries)
-- ----------------------------------------------------------------------------
SELECT 
    ngo_id, 
    name, 
    city, 
    phone, 
    email
FROM ngos
WHERE is_verified = TRUE
  AND ngo_id NOT IN (SELECT DISTINCT ngo_id FROM claims);

-- ----------------------------------------------------------------------------
-- 5. Student vs Canteen breakdown: Which source has the most surplus?
-- ----------------------------------------------------------------------------
SELECT 
    food_source,
    COUNT(*) AS total_listings,
    SUM(quantity_servings) AS total_servings,
    ROUND(AVG(quantity_servings), 1) AS avg_servings_per_listing
FROM food_listings
GROUP BY food_source
ORDER BY total_servings DESC;

